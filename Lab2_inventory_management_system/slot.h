#ifndef SLOT_H
#define SLOT_H

#include <iostream>


/**
 * @brief A slot of the inventory, i.e. a node of a doubly-linked list, which stores items with the same name up to a maximum number of items.
 *
 * Constructing a slot links it into a list, and destroying a slot unlinks it from its list,
 * so that the list always stays consistent.
 */
class Slot {
    // data members
    private:
    /**
     * @brief The name of the items in this slot.
     */
    char* m_name;
    /**
     * @brief The number of items in this slot.
     */
    int m_count;
    /**
     * @brief The pointer to the previous slot.
     */
    Slot* m_prev;
    /**
     * @brief The pointer to the next slot.
     */
    Slot* m_next;
    /**
     * @brief The maximum number of items held by this slot.
     */
    int m_max_items;

    // constructors and destructor
    public:
    /**
     * @brief Initializes an empty slot (holding 0 items) with a deep copy of the given name,
     * and links it into the list right after prev.
     *
     * If prev is nullptr, the slot is not linked to any other slot, i.e. its prev and next are nullptr.
     *
     * @param name Name of the items this slot stores.
     *
     * @param max_items Maximum number of items held by this slot, assumed to be the same for items with the same name.
     *
     * @param prev The slot after which this slot is linked, or nullptr.
     */
    Slot(const char* name, int max_items, Slot* prev);
    /**
     * @brief Initializes a new slot holding the same items as other (the same name, deep copied, the same count and the same maximum number of items),
     * and links it into the list right after prev.
     *
     * other is only read: it keeps its items, and it does not move.
     * Where the new slot goes is decided by prev alone, like with the other constructor.
     *
     * @param other The slot whose items are copied. It is not modified.
     *
     * @param prev The slot after which this slot is linked, or nullptr.
     */
    Slot(const Slot& other, Slot* prev);
    /**
     * @brief Unlinks this slot from its list by linking its previous and next slots to each other,
     * and deallocates the memory dynamically allocated by this slot.
     */
    ~Slot();

    // A slot always has a position in a list, so it can never be created without being given one.
    // The copy constructor generated by the compiler would do exactly that,
    // and the generated copy assignment would overwrite the m_prev and m_next of an existing slot, breaking its list.
    Slot(const Slot&) = delete;
    Slot& operator=(const Slot&) = delete;

    // given functions
    public:
    // accessors

    /**
     * @return The name of the items in this slot.
     */
    const char* get_name() const { return m_name; }
    /**
     * @return The number of items in this slot.
     */
    int get_count() const { return m_count; }
    /**
     * @return The maximum number of items this slot can hold.
     */
    int get_max_items() const { return m_max_items; }
    /**
     * @return The previous slot (can be nullptr).
     */
    const Slot* get_prev() const { return m_prev; }
    /**
     * @return The next slot (can be nullptr).
     */
    const Slot* get_next() const { return m_next; }
    /**
     * @return The previous slot (can be nullptr).
     */
    Slot* get_prev() { return m_prev; }
    /**
     * @return The next slot (can be nullptr).
     */
    Slot* get_next() { return m_next; }

    // mutators

    /**
     * @brief Fills up the slot, while ensuring that the count does not exceed m_max_items.
     *
     * @param amount Number of items to fill up the slot with.
     *
     * @return Number of items not filled because the slot reached m_max_items.
     */
    int fill(int amount) {
        m_count += amount;
        if (m_count > m_max_items) {
            int leftover = m_count - m_max_items;
            m_count = m_max_items;
            return leftover;
        } else {
            return 0;
        }
    }
    /**
     * @brief Takes items away from the slot, while ensuring that the count does not drop below 0.
     *
     * @param amount Number of items to take away.
     *
     * @return Number of items not taken because the slot became empty.
     */
    int take(int amount) {
        m_count -= amount;
        if (m_count < 0) {
            int untaken = -m_count;
            m_count = 0;
            return untaken;
        } else {
            return 0;
        }
    }

    // debugging

    /**
     * @brief Prints this slot on one line, for debugging: its name, its count, its maximum number of items,
     * and the names of the slots linked before and after it.
     *
     * This function is given only to help you debug, and the tests never call it.
     * Never leave a call to it in the code you hand in: the tests compare what your program prints,
     * so any extra output makes them fail.
     */
    void debug_print() const {
        std::cout << "\"" << (m_name != nullptr ? m_name : "(null)") << "\" "
                  << m_count << "/" << m_max_items << " (prev ";
        if (m_prev == nullptr)
            std::cout << "none";
        else
            std::cout << "\"" << (m_prev->m_name != nullptr ? m_prev->m_name : "(null)") << "\"";
        std::cout << ", next ";
        if (m_next == nullptr)
            std::cout << "none";
        else
            std::cout << "\"" << (m_next->m_name != nullptr ? m_next->m_name : "(null)") << "\"";
        std::cout << ")\n";
    }
};

#endif
